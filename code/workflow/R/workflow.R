# Frozen-file register (010-input-manifest)

rwv_register_read <- function(step, file = "metadata/frozen-files.tsv") {
  if (!file %in% rwv_chr(step$spec$project_inputs)) {
    rwv_fail(step$name, " does not declare project input ", file, " in config/workflow.yml.")
  }
  path <- file.path(step$root, file)
  if (!file.exists(path)) rwv_fail("Missing register ", file, ".")
  reg <- rwv_read_tsv(path)
  cols <- c("path", "role", "sha256", "origin", "source_sha256", "note")
  if (!identical(names(reg), cols)) rwv_fail(file, " must have the columns: ", paste(cols, collapse = ", "), ".")
  if (!nrow(reg) || anyDuplicated(reg$path) || any(grepl("^/|(^|/)\\.\\.(/|$)", reg$path))) {
    rwv_fail(file, ": paths must be unique and project-relative.")
  }
  if (!all(grepl("^[0-9a-f]{64}$", reg$sha256))) rwv_fail(file, ": every sha256 must be 64 lowercase hex characters.")
  rwv_step_note_input(step, "project", file, rwv_sha256(path))
  reg
}

rwv_register_verify <- function(step, register) {
  paths <- file.path(step$root, register$path)
  found <- file.exists(paths)
  actual <- rep(NA_character_, length(paths))
  actual[found] <- rwv_sha256(paths[found])
  status <- ifelse(!found, "missing", ifelse(actual == register$sha256, "match", "mismatch"))
  out <- data.frame(
    path = register$path, role = register$role,
    bytes = ifelse(found, file.size(paths), NA_real_),
    sha256 = actual, expected_sha256 = register$sha256, status = status,
    origin = register$origin, source_sha256 = register$source_sha256
  )
  bad <- out[out$status != "match", , drop = FALSE]
  if (nrow(bad)) {
    rwv_fail("Frozen inputs failed verification against metadata/frozen-files.tsv:\n",
             paste0("  ", bad$status, ": ", bad$path, collapse = "\n"),
             "\nIf a change was deliberate, update its sha256 in the register and record why in docs/README.md.")
  }
  for (i in seq_len(nrow(out))) rwv_step_note_input(step, "project", out$path[i], out$sha256[i])
  out
}

