# Report and bundle synchronisation (scripts/check-sync.R, scripts/render.R)

# The HTML and Markdown reports of a step must come from the execution that
# wrote its current step-record.json: both exist, the Markdown was derived
# after the HTML, and both print every recorded output hash (the "Outputs
# recorded" table of each QMD). Returns problems as text (empty = in sync).
rwv_report_sync <- function(root, id) {
  wf <- rwv_workflow_read(root)
  spec <- rwv_workflow_step(wf, id)
  rec_path <- file.path(root, wf$workflow_dir, "data", id, "step-record.json")
  html <- file.path(root, sub("\\.qmd$", ".html", spec$qmd))
  md <- file.path(root, sub("\\.qmd$", ".md", spec$qmd))
  if (!file.exists(rec_path)) return(paste0(id, ": no step-record.json; render the step"))
  bad <- character(0)
  if (!file.exists(html)) bad <- c(bad, paste0(id, ": HTML report missing"))
  if (!file.exists(md)) bad <- c(bad, paste0(id, ": Markdown report missing"))
  if (length(bad)) return(bad)
  c(bad, rwv_report_sync_check(id, html, md, rwv_step_record_read(rec_path, id)))
}

rwv_report_sync_check <- function(id, html, md, record) {
  bad <- character(0)
  # The hook gives the Markdown report the HTML's time stamp (whole seconds).
  if (as.numeric(file.mtime(md)) + 1 < as.numeric(file.mtime(html))) bad <- c(bad, paste0(id, ": Markdown report is older than the HTML report"))
  prefixes <- substr(vapply(record$outputs, function(o) o$sha256, character(1)), 1, 16)
  for (f in c(html, md)) {
    txt <- paste(readLines(f, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
    miss <- prefixes[!vapply(prefixes, function(p) grepl(p, txt, fixed = TRUE), logical(1))]
    if (length(miss)) {
      bad <- c(bad, paste0(id, ": ", basename(f), " does not show ", length(miss), " of the ", length(prefixes),
                           " output hashes in step-record.json (run ", record$run_id, "): it is from another execution"))
    }
  }
  bad
}

# The review bundle must copy the current upstream files: every row of
# bundle-manifest.tsv is compared with the file now in its source step.
rwv_bundle_sync <- function(root, bundle_step = "900-publication-bundle") {
  wf <- rwv_workflow_read(root)
  data_dir <- file.path(root, wf$workflow_dir, "data")
  man_path <- file.path(data_dir, bundle_step, "bundle-manifest.tsv")
  if (!file.exists(man_path)) return(paste0(bundle_step, ": no bundle-manifest.tsv; render ", bundle_step))
  rwv_bundle_sync_check(as.data.frame(rwv_read_tsv(man_path)), data_dir, bundle_step)
}

rwv_bundle_sync_check <- function(man, data_dir, bundle_step = "900-publication-bundle") {
  src <- file.path(data_dir, man$source_step, man$source_file)
  now <- vapply(src, function(f) if (file.exists(f)) rwv_sha256(f) else NA_character_, character(1), USE.NAMES = FALSE)
  stale <- is.na(now) | now != man$source_sha256
  if (!any(stale)) return(character(0))
  paste0(bundle_step, ": ", sum(stale), " bundled file(s) no longer match their source (",
         paste(utils::head(paste0(man$source_step[stale], "/", man$source_file[stale]), 6), collapse = ", "),
         if (sum(stale) > 6) ", ..." else "", "); re-render ", bundle_step)
}

# Inputs recorded by a step (project files, raw inputs, upstream outputs)
# compared with the files now on disk: a step whose inputs changed after it
# ran is out of date even if its own outputs are intact.
rwv_step_inputs_changed <- function(root, id) {
  rec_path <- file.path(root, "analyses", "data", id, "step-record.json")
  if (!file.exists(rec_path)) return(character(0))
  rec <- jsonlite::read_json(rec_path)
  changed <- rwv_source_changes(root, id, rec)
  for (i in rec$inputs) {
    if (identical(i$kind, "upstream")) {
      p <- file.path(root, "analyses", "data", i$path)
    } else {
      p <- file.path(root, i$path)
    }
    if (!file.exists(p) || !identical(rwv_sha256(p), i$sha256)) {
      # The whole-file hash of the 010 manifest also changes when only review or
      # publication metadata is registered; such a change is accepted only by the
      # consumer-scoped comparison below. Every other input stays byte-compared.
      if (identical(i$kind, "upstream") && identical(i$path, rwv_manifest_upstream) && file.exists(p) &&
          isTRUE(rwv_manifest_reuse(root, id, i$sha256)$reusable)) next
      changed <- c(changed, i$path)
    }
  }
  unique(changed)
}

# ---------------------------------------------------------------------------
# Consumer-scoped reuse of the 010 input manifest (v50 release engineering, 2026-10-19;
# Codex task book docs/figure-cleanup-v49-2026-10-19/03, author-approved).
#
# Every step records the SHA of the WHOLE 010 input-manifest.tsv. Registering a
# visual review or a review report changes that file although no scientific input
# changed. A recorded manifest SHA that differs from the current one is accepted
# for a step only when all of the following hold; otherwise the step stays out of
# date exactly as before:
#   1. the recorded manifest is available in archive/manifest-history/ under its
#      own SHA and its bytes hash to that SHA (no history file, no reuse);
#   2. the current manifest is the output listed by a complete 010 step record;
#   3. both manifests have the known column schema, unique paths and rows;
#   4. every row that differs (added, removed or any field changed) is review or
#      publication metadata: rwv_publication_metadata_paths, or a row whose role is
#      review-report in every version where it exists; or config/workflow.yml when
#      the workflow-level fields and this step's own definition are identical in
#      the recorded (history, hash-verified) and the current workflow.yml.
# Files the step read itself (project, raw, upstream) are still compared byte by
# byte above, so a step that reads a changed register (900) is out of date.
# Nothing here rewrites a record; reuse is a re-verification, not a re-execution.

rwv_manifest_upstream <- "010-input-manifest/input-manifest.tsv"
rwv_manifest_columns <- c("path", "role", "bytes", "sha256", "expected_sha256", "status", "origin", "source_sha256")
rwv_publication_metadata_paths <- c("metadata/visual-review.tsv", "metadata/review-log.tsv", "metadata/frozen-files.tsv")

# A content-addressed history file: archive/manifest-history/<stem>-<sha256>.<ext>.
rwv_history_file <- function(root, stem, sha, ext) {
  if (!is.character(sha) || length(sha) != 1L || !grepl("^[0-9a-f]{64}$", sha)) return(NULL)
  p <- file.path(root, "archive", "manifest-history", paste0(stem, "-", sha, ".", ext))
  if (!file.exists(p) || !identical(rwv_sha256(p), sha)) return(NULL)
  p
}

rwv_workflow_step_unchanged <- function(root, id, old_sha, new_sha) {
  old_p <- rwv_history_file(root, "workflow", old_sha, "yml")
  new_p <- file.path(root, "config", "workflow.yml")
  if (is.null(old_p) || !file.exists(new_p) || !identical(rwv_sha256(new_p), new_sha)) return(FALSE)
  a <- tryCatch(yaml::read_yaml(old_p), error = function(e) NULL)
  b <- tryCatch(yaml::read_yaml(new_p), error = function(e) NULL)
  if (!is.list(a) || !is.list(b) || !is.list(a$steps) || !is.list(b$steps)) return(FALSE)
  if (!identical(a[setdiff(names(a), "steps")], b[setdiff(names(b), "steps")])) return(FALSE)
  sa <- Filter(function(s) identical(s$id, id), a$steps)
  sb <- Filter(function(s) identical(s$id, id), b$steps)
  length(sa) == 1L && length(sb) == 1L && identical(sa[[1]], sb[[1]])
}

rwv_manifest_reuse <- function(root, id, recorded_sha) {
  res <- function(ok, reason, changed = character(0), blocking = character(0))
    list(step = id, reusable = ok, reason = reason, recorded_sha256 = recorded_sha, changed_paths = changed, blocking_paths = blocking)
  old_path <- rwv_history_file(root, "input-manifest", recorded_sha, "tsv")
  if (is.null(old_path)) return(res(FALSE, "recorded 010 manifest is not in archive/manifest-history or does not hash to its SHA"))
  d <- file.path(root, "analyses", "data", "010-input-manifest")
  cur_path <- file.path(d, "input-manifest.tsv")
  rec_path <- file.path(d, "step-record.json")
  if (!file.exists(cur_path) || !file.exists(rec_path)) return(res(FALSE, "010 has no current manifest or step record"))
  r010 <- jsonlite::read_json(rec_path)
  hit <- Filter(function(o) identical(o$file, "input-manifest.tsv"), r010$outputs)
  if (!identical(r010$status, "complete") || length(hit) != 1L || !identical(hit[[1]]$sha256, rwv_sha256(cur_path))) {
    return(res(FALSE, "current 010 manifest is not the output of a complete 010 step record"))
  }
  old <- as.data.frame(rwv_read_tsv(old_path))
  new <- as.data.frame(rwv_read_tsv(cur_path))
  if (!identical(names(old), rwv_manifest_columns) || !identical(names(new), rwv_manifest_columns)) {
    return(res(FALSE, "unknown 010 manifest schema"))
  }
  if (anyDuplicated(old$path) || anyDuplicated(new$path) || !nrow(old) || !nrow(new)) {
    return(res(FALSE, "010 manifest has duplicated paths or no rows"))
  }
  row_key <- function(x) stats::setNames(do.call(paste, c(unname(as.list(x)), sep = "\t")), x$path)
  ko <- row_key(old)
  kn <- row_key(new)
  paths <- union(names(ko), names(kn))
  changed <- paths[is.na(ko[paths]) | is.na(kn[paths]) | ko[paths] != kn[paths]]
  role_old <- stats::setNames(old$role, old$path)
  role_new <- stats::setNames(new$role, new$path)
  sha_old <- stats::setNames(old$sha256, old$path)
  sha_new <- stats::setNames(new$sha256, new$path)
  blocking <- character(0)
  for (p in changed) {
    if (p %in% rwv_publication_metadata_paths) next
    roles <- stats::na.omit(c(role_old[p], role_new[p]))
    if (length(roles) && all(roles == "review-report")) next
    if (identical(p, "config/workflow.yml") && p %in% names(sha_old) && p %in% names(sha_new) &&
        rwv_workflow_step_unchanged(root, id, unname(sha_old[p]), unname(sha_new[p]))) next
    blocking <- c(blocking, p)
  }
  if (length(blocking)) return(res(FALSE, "a non-publication row of the 010 manifest changed", changed, blocking))
  res(TRUE, if (length(changed)) "only review/publication metadata changed in the 010 manifest" else "manifest rows identical",
      changed)
}

# Visual-review state of one figure (used by 900): the current PNG must match exactly one
# registered row; a hash registered twice is not accepted (no silent duplicate rows).
rwv_visual_review_state <- function(visual, key, png_sha) {
  all <- visual[visual$figure_key == key, , drop = FALSE]
  vr <- all[all$png_sha256 == png_sha, , drop = FALSE]
  if (nrow(vr) == 1L) return(sprintf("%s by %s on %s", vr$verdict, vr$reviewer, vr$date))
  if (nrow(vr) > 1L) return("not current: this PNG hash is registered more than once")
  if (nrow(all) >= 1L) return("not current: the registered hash is from an earlier version of this PNG")
  "not reviewed"
}

# Per-step view used by scripts/check-sync.R and the release validation record:
# which steps carry an older 010 manifest SHA, and whether it is reusable.
rwv_manifest_reuse_status <- function(root) {
  cur <- file.path(root, "analyses", "data", rwv_manifest_upstream)
  cur_sha <- if (file.exists(cur)) rwv_sha256(cur) else NA_character_
  out <- list()
  for (rec_path in Sys.glob(file.path(root, "analyses", "data", "[0-9][0-9][0-9]-*", "step-record.json"))) {
    rec <- jsonlite::read_json(rec_path)
    hit <- Filter(function(i) identical(i$kind, "upstream") && identical(i$path, rwv_manifest_upstream), rec$inputs)
    if (length(hit) != 1L || identical(hit[[1]]$sha256, cur_sha)) next
    r <- rwv_manifest_reuse(root, rec$step, hit[[1]]$sha256)
    out[[length(out) + 1L]] <- data.frame(step = rec$step, run_id = rec$run_id, recorded_sha256 = r$recorded_sha256,
      current_sha256 = cur_sha, reusable = r$reusable, reason = r$reason,
      changed_paths = paste(r$changed_paths, collapse = ";"), blocking_paths = paste(r$blocking_paths, collapse = ";"))
  }
  if (length(out)) do.call(rbind, out) else data.frame()
}


# Everything that makes one step not current: reports from another execution,
# inputs changed since it ran, an interrupted publication, or a latest run
# that did not finish. Returns problems as text (empty = current).
rwv_step_sync_problems <- function(root, id) {
  problems <- rwv_report_sync(root, id)
  ch <- rwv_step_inputs_changed(root, id)
  if (length(ch)) problems <- c(problems, paste0(id, ": inputs changed since it ran (", paste(utils::head(ch, 3), collapse = ", "),
                                                 if (length(ch) > 3) ", ..." else "", "); render it again"))
  d <- file.path(root, "analyses", "data", id)
  if (file.exists(file.path(d, ".rwv-publish.json"))) problems <- c(problems, paste0(id, ": publication was interrupted; render it again"))
  st <- rwv_stage_status_read(d)
  if (!is.null(st) && st$status %in% c("running", "failed")) {
    problems <- c(problems, paste0(id, ": latest run ", st$run_id, " did not finish (", rwv_stage_status_label(st), "); the previous result is kept but not current"))
  }
  problems
}

# Project-wide sync state used by scripts/check-sync.R.
# Daily steps and the review bundle must always be current (problems).
# Optional checks (014, 090) are skipped by the daily scripts/render.R, so in
# the daily mode an optional check that was never run or is out of date is a
# note, not a failure; the note still names it, so a stale comparison is never
# hidden. With strict = TRUE (render.R --with-checks) they must be current too.
# step_problems is a parameter only so the self-test can inject a stale state
# without touching real outputs.
rwv_sync_status <- function(root, strict = FALSE, step_problems = rwv_step_sync_problems) {
  wf_steps <- rwv_workflow_read(root)$steps
  ids <- vapply(wf_steps, function(s) s$id, character(1))
  optional <- ids[vapply(wf_steps, function(s) isTRUE(s[["optional"]]), logical(1))]
  daily <- setdiff(ids, optional)
  has_record <- function(id) file.exists(file.path(root, "analyses", "data", id, "step-record.json"))
  not_run <- optional[!vapply(optional, has_record, logical(1))]
  ran <- setdiff(optional, not_run)
  problems <- unlist(lapply(daily, function(id) step_problems(root, id)))
  opt_problems <- unlist(lapply(ran, function(id) step_problems(root, id)))
  stale_opt <- unique(sub(":.*$", "", opt_problems))
  notes <- character(0)
  if (strict) {
    problems <- c(problems, opt_problems,
                  if (length(not_run)) paste0(not_run, ": optional check has not been run; render it (strict mode)"))
  } else {
    if (length(not_run)) notes <- c(notes, paste0("Optional checks not run yet: ", paste(not_run, collapse = ", ")))
    if (length(opt_problems)) {
      notes <- c(notes, paste0("Optional checks out of date (they do not block the daily result, but re-run them before ",
                               "relying on them, e.g. after a method or style change): ", paste(opt_problems, collapse = "; ")))
    }
  }
  problems <- c(problems, rwv_bundle_sync(root))
  checked <- c(daily, if (strict) optional else setdiff(ran, stale_opt))
  runs <- vapply(c(daily, ran), function(id) {
    f <- file.path(root, "analyses", "data", id, "step-record.json")
    if (file.exists(f)) jsonlite::read_json(f)$run_id else NA_character_
  }, character(1))
  list(problems = problems, notes = notes, strict = strict, daily = daily, optional = optional,
       not_run = not_run, stale_optional = stale_opt, checked = checked,
       runs = unique(stats::na.omit(runs)))
}
