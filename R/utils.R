# Processed analysis inputs (analyses/data/inputs.tsv)

rwv_raw_cols <- c("path", "consumer_step", "sha256", "origin_project", "origin_path", "origin_sha256",
                  "origin_git_commit", "origin_git_state", "transform", "fields_units", "note")

rwv_raw_register_read <- function(step, file = "analyses/data/inputs.tsv") {
  if (!file %in% rwv_chr(step$spec$project_inputs)) {
    rwv_fail(step$name, " does not declare project input ", file, " in analyses/R/steps.yml.")
  }
  path <- file.path(step$root, file)
  if (!file.exists(path)) rwv_fail("Missing raw-input register ", file, ".")
  reg <- rwv_read_tsv(path)
  if (!identical(names(reg), rwv_raw_cols)) rwv_fail(file, " must have the columns: ", paste(rwv_raw_cols, collapse = ", "), ".")
  ok_path <- grepl("^analyses/data/00-raw/d[0-9]{3}-[a-z0-9-]+/[^/]+$", reg$path)
  if (!nrow(reg) || anyDuplicated(reg$path) || !all(ok_path)) {
    rwv_fail(file, ": paths must be unique files directly inside analyses/data/00-raw/d<step>/.")
  }
  if (!all(grepl("^[0-9a-f]{64}$", c(reg$sha256, reg$origin_sha256)))) rwv_fail(file, ": malformed sha256.")
  owner <- sub("^analyses/data/00-raw/d([^/]+)/.*$", "\\1", reg$path)
  if (!identical(owner, reg$consumer_step)) rwv_fail(file, ": each input must sit in the raw area of its consumer step.")
  rwv_step_note_input(step, "project", file, rwv_sha256(path))
  reg
}

# Hash every registered raw input and refuse unregistered files in raw areas.
rwv_raw_register_verify <- function(step, reg, path_raw) {
  paths <- file.path(step$root, reg$path)
  found <- file.exists(paths)
  actual <- rep(NA_character_, length(paths))
  actual[found] <- rwv_sha256(paths[found])
  status <- ifelse(!found, "missing", ifelse(actual == reg$sha256, "match", "mismatch"))
  bad <- reg$path[status != "match"]
  if (length(bad)) {
    rwv_fail("Raw inputs failed verification against analyses/data/inputs.tsv:\n",
             paste0("  ", status[status != "match"], ": ", bad, collapse = "\n"),
             "\nSupply the exact registered input files; do not substitute unregistered data.")
  }
  present <- list.files(path_raw, recursive = TRUE, all.files = TRUE, no.. = TRUE)
  present <- present[basename(present) != ".DS_Store"]
  present <- file.path("analyses/data/00-raw", present)
  extra <- setdiff(present, reg$path)
  if (length(extra)) {
    rwv_fail("Unregistered files in analyses/data/00-raw/ (not accepted as inputs): ", paste(extra, collapse = ", "))
  }
  data.frame(path = reg$path, consumer_step = reg$consumer_step, bytes = file.size(paths), sha256 = actual,
             status = status, origin_path = reg$origin_path, origin_sha256 = reg$origin_sha256,
             origin_git_commit = reg$origin_git_commit, origin_git_state = reg$origin_git_state,
             transform = reg$transform)
}

# Read a registered raw input of the current step (from its own d<step>/ area),
# requiring the hash recorded by 010-input-manifest.
# Registered raw inputs that the active analysis version deliberately does not
# read (for example the archived community tables when 020 reads the rebuilt
# results). Each file is still verified against its registered hash and is
# recorded in step-record.json as not used, so the "never read" guard of
# rwv_step_finish() cannot be satisfied by silence.
rwv_raw_not_used <- function(step, path_data, files, raw_manifest) {
  for (f in files) {
    p <- rwv_raw_input(step, path_data, f, raw_manifest)
    step$inputs[[length(step$inputs)]]$kind <- "raw_not_used_in_active_version"
  }
  invisible(files)
}

rwv_raw_input <- function(step, path_data, file, raw_manifest) {
  rel <- file.path("analyses/data/00-raw", paste0("d", step$name), file)
  row <- raw_manifest[raw_manifest$path == rel, , drop = FALSE]
  if (nrow(row) != 1L) rwv_fail(rel, " is not a registered raw input (analyses/data/inputs.tsv).")
  if (!identical(row$consumer_step, step$name)) rwv_fail(rel, " belongs to ", row$consumer_step, ", not ", step$name, ".")
  path <- file.path(path_data, file)
  if (!identical(rwv_norm(path), rwv_norm(file.path(step$root, rel)))) {
    rwv_fail("path_data does not point at ", dirname(rel), ". Re-run the setup chunk.")
  }
  actual <- rwv_sha256(path)
  if (!identical(actual, row$sha256)) rwv_fail(rel, " changed after 010-input-manifest verified it. Re-run from 010.")
  rwv_step_note_input(step, "raw", rel, actual)
  path
}

