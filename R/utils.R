# Workflow guards for the RecWaterVirome qproj project: project root, the
# explicit step manifest (analyses/R/steps.yml), step ownership, earlier-source
# checks, the frozen-file register, hashing and step records.
# Authors (display order): Jinlong Ru, Cunli Pan
#
# Pure function definitions: nothing in this file runs at load_all() time.

rwv_fail <- function(...) {
  stop(paste0(...), call. = FALSE)
}

rwv_chr <- function(x) {
  if (is.null(x) || length(x) == 0L) character(0) else as.character(unlist(x, use.names = FALSE))
}

rwv_norm <- function(path) {
  normalizePath(path, winslash = "/", mustWork = FALSE)
}

rwv_time <- function(time = Sys.time()) {
  format(time, "%Y-%m-%dT%H:%M:%S%z")
}

# Project root = the directory whose DESCRIPTION declares this package.
rwv_root <- function(path = getwd()) {
  criterion <- rprojroot::has_file("DESCRIPTION", contents = "^Package: RecWaterVirome$")
  rprojroot::find_root(criterion, path = path)
}

rwv_sha256 <- function(path) {
  missing <- path[!file.exists(path)]
  if (length(missing)) rwv_fail("Cannot hash missing file(s): ", paste(missing, collapse = ", "))
  unname(vapply(path, function(p) digest::digest(file = p, algo = "sha256"), character(1)))
}

# Conservative executable-source contract. All shared R files are loaded by
# pkgload, so adding or deleting a helper is also a source change. Reports,
# data and self-test scripts are not executable dependencies of a step.
rwv_source_files <- function(root, id) {
  shared <- list.files(file.path(root, "R"), pattern = "[.]R$", full.names = FALSE)
  sort(unique(c(paste0("analyses/", id, ".qmd"), paste0("R/", shared),
                "DESCRIPTION", "NAMESPACE", "analyses/_quarto.yml",
                "dev/render.R", "dev/render.R")))
}

rwv_source_snapshot <- function(root, id) {
  paths <- rwv_source_files(root, id)
  hashes <- rwv_sha256(file.path(root, paths))
  lapply(seq_along(paths), function(i) list(path = paths[i], sha256 = hashes[i]))
}

rwv_source_changes <- function(root, id, record) {
  # Historical records remain valid historical evidence, but cannot certify
  # that their outputs were generated by the current executable sources.
  if (!identical(record$source_contract, "rwv-source-public-v2") || !length(record$sources)) {
    return("<source provenance unavailable: render this step before reuse>")
  }
  expected <- rwv_source_files(root, id)
  entries <- record$sources
  valid <- vapply(entries, function(x) is.list(x) && is.character(x$path) &&
    length(x$path) == 1L && !is.na(x$path) && is.character(x$sha256) &&
    length(x$sha256) == 1L && !is.na(x$sha256) && grepl("^[0-9a-f]{64}$", x$sha256), logical(1))
  if (!all(valid)) return("<invalid source provenance>")
  recorded <- vapply(entries, `[[`, "", "path")
  if (anyDuplicated(recorded)) return("<duplicate source provenance>")
  # Only expected project-relative paths are ever accessed, including when
  # a malformed record contains an absolute path or a parent traversal.
  changed <- union(setdiff(expected, recorded), setdiff(recorded, expected))
  for (entry in entries[recorded %in% expected]) {
    p <- file.path(root, entry$path)
    if (!file.exists(p) || !identical(rwv_sha256(p), entry$sha256)) changed <- c(changed, entry$path)
  }
  unique(changed)
}

rwv_read_tsv <- function(path) {
  readr::read_tsv(path,
    col_types = readr::cols(.default = readr::col_character()),
    na = character(), progress = FALSE, lazy = FALSE
  )
}

rwv_write_tsv <- function(x, path) {
  readr::write_tsv(x, path, na = "NA")
  invisible(path)
}

# qproj's path_target() joins all of its arguments into ONE path
# (path_target(c("a", "b")) is data/<step>/a/b), so build one path per file.
rwv_target_files <- function(path_target, files) {
  vapply(files, function(f) path_target(f), character(1), USE.NAMES = FALSE)
}

# A plain file or directory name: no path separators, not "." or "..".
rwv_is_plain_name <- function(x) {
  grepl("^[A-Za-z0-9][A-Za-z0-9._-]*$", x) & !x %in% c(".", "..")
}

rwv_is_link <- function(path) {
  nzchar(Sys.readlink(path))
}

# Resolve a declared output directory and check that it is a real, direct
# child of the step directory (never a link, never outside).
rwv_output_dir_path <- function(path_target, d) {
  if (!isTRUE(rwv_is_plain_name(d))) rwv_fail("Invalid output directory name: ", d)
  step_dir <- rwv_norm(path_target())
  dir <- path_target(d)
  if (file.exists(dir) && rwv_is_link(dir)) rwv_fail("Output directory ", dir, " is a symbolic link; refusing to use it.")
  if (dir.exists(dir) && !identical(dirname(rwv_norm(dir)), step_dir)) {
    rwv_fail("Output directory ", dir, " does not resolve to a direct child of ", step_dir, ".")
  }
  dir
}


# ---------------------------------------------------------------------------
# Explicit step manifest

rwv_workflow_read <- function(root = rwv_root()) {
  path <- file.path(root, "analyses", "R", "steps.yml")
  if (!file.exists(path)) rwv_fail("Workflow manifest not found: ", path)
  wf <- yaml::read_yaml(path)
  rwv_workflow_check(wf, root)
  wf
}

rwv_workflow_ids <- function(wf) {
  vapply(wf$steps, function(s) as.character(s$id), character(1))
}

rwv_workflow_step <- function(wf, id) {
  ids <- rwv_workflow_ids(wf)
  if (!id %in% ids) {
    rwv_fail("Step '", id, "' is not declared in analyses/R/steps.yml (declared: ", paste(ids, collapse = ", "), ").")
  }
  wf$steps[[match(id, ids)]]
}

rwv_step_number <- function(id) {
  as.integer(substr(id, 1L, 3L))
}

rwv_workflow_check <- function(wf, root) {
  bad <- function(...) rwv_fail("analyses/R/steps.yml: ", ...)
  if (!identical(as.integer(wf$version), 1L)) bad("unsupported version.")
  if (!identical(wf$workflow_dir, "analyses")) bad("workflow_dir must be 'analyses'.")
  if (!length(wf$steps)) bad("no steps declared.")
  ids <- rwv_workflow_ids(wf)
  if (anyDuplicated(ids)) bad("duplicated step ids.")
  if (!all(grepl("^[0-9]{3}-[a-z0-9]+(-[a-z0-9]+)*$", ids)) || any(startsWith(ids, "00"))) {
    bad("step ids must be three-digit zero-padded names outside the reserved 00- range.")
  }
  if (is.unsorted(rwv_step_number(ids), strictly = TRUE)) bad("steps must be listed in increasing numeric order.")
  for (i in seq_along(wf$steps)) {
    s <- wf$steps[[i]]
    id <- ids[i]
    qmd <- file.path(wf$workflow_dir, paste0(id, ".qmd"))
    if (!identical(s$qmd, qmd)) bad(id, ": qmd must be ", qmd, ".")
    if (!file.exists(file.path(root, qmd))) bad(id, ": missing ", qmd, ".")
    deps <- rwv_chr(s$depends_on)
    if (!all(deps %in% ids[seq_len(i - 1L)])) bad(id, ": depends_on may only name steps listed before it.")
    # Optional steps (checks run on demand) may depend on daily steps, never
    # the other way round, so the daily workflow runs without them.
    opt <- s[["optional"]]
    if (!is.null(opt) && !(is.logical(opt) && length(opt) == 1L)) bad(id, ": optional must be true or false.")
    optional_ids <- ids[vapply(wf$steps, function(z) isTRUE(z[["optional"]]), logical(1))]
    if (!isTRUE(opt) && any(deps %in% optional_ids)) bad(id, ": a daily step may not depend on an optional step.")
    outputs <- rwv_chr(s$outputs)
    if (!length(outputs) || anyDuplicated(outputs) || any(outputs != basename(outputs)) ||
      "step-record.json" %in% outputs) {
      bad(id, ": outputs must be unique flat file names (step-record.json is implicit).")
    }
    dirs <- rwv_chr(s$output_dirs)
    if (length(dirs) && (anyDuplicated(dirs) || !all(rwv_is_plain_name(dirs)) || any(dirs %in% outputs))) {
      bad(id, ": output_dirs must be unique plain directory names (letters, digits, '.', '_', '-'; ",
          "not '.' or '..') that are not also outputs.")
    }
    optional <- rwv_chr(s$optional_outputs)
    if (length(optional) && (anyDuplicated(optional) || !all(rwv_is_plain_name(optional)) ||
      any(optional %in% c(outputs, dirs, "step-record.json")))) {
      bad(id, ": optional_outputs must be unique plain file names that are neither outputs nor output_dirs.")
    }
    inputs <- rwv_chr(s$project_inputs)
    if (any(grepl("^/|(^|/)\\.\\.(/|$)", inputs))) bad(id, ": project_inputs must be project-relative.")
    missing <- inputs[!file.exists(file.path(root, inputs))]
    if (length(missing)) bad(id, ": missing project inputs ", paste(missing, collapse = ", "), ".")
    for (u in s$upstream_inputs) {
      if (!isTRUE(u$step %in% deps)) bad(id, ": upstream input from undeclared dependency ", u$step, ".")
      if (!isTRUE(u$file %in% rwv_chr(rwv_workflow_step(wf, u$step)$outputs))) {
        bad(id, ": ", u$step, " does not declare output ", u$file, ".")
      }
    }
  }
  invisible(TRUE)
}

# ---------------------------------------------------------------------------
# Staged outputs: a step never deletes its last successful result up front.
#
# While a step runs, its new outputs are written to <step>/.rwv-staging/ and
# <step>/.rwv-status.json says "running". rwv_step_finish() checks the staged
# set and publishes it: it writes a journal (.rwv-publish.json), moves the
# previous result into .rwv-previous/, moves the new files in, and commits by
# renaming the new step-record.json into place (a single atomic rename). If a
# run fails or is killed before that, the previous result and its record are
# untouched; if publication itself is interrupted, rwv_stage_recover() uses the
# journal to finish (record committed) or to restore the previous result (not
# committed). A "running" or "failed" status stops downstream steps from
# taking the kept previous result for the outcome of the latest run.

rwv_stage_names <- list(staging = ".rwv-staging", previous = ".rwv-previous",
                        status = ".rwv-status.json", journal = ".rwv-publish.json")

rwv_stage_child <- function(final, name) {
  p <- file.path(final, name)
  if (file.exists(p) && rwv_is_link(p)) rwv_fail(p, " is a symbolic link; refusing to use it.")
  p
}

rwv_stage_status_write <- function(final, fields) {
  tmp <- file.path(final, paste0(rwv_stage_names$status, ".tmp"))
  jsonlite::write_json(fields, tmp, auto_unbox = TRUE, pretty = TRUE)
  file.rename(tmp, file.path(final, rwv_stage_names$status))
}

rwv_stage_status_read <- function(final) {
  p <- file.path(final, rwv_stage_names$status)
  if (file.exists(p)) jsonlite::read_json(p) else NULL
}

rwv_stage_host <- function() unname(Sys.info()[["nodename"]])

# A step that stops on an R or Quarto error never reaches rwv_step_finish(), so its
# status stays "running". Describe that state accurately: if the recorded process
# no longer exists on this host, the run ended without finishing. The status file
# itself is not rewritten and downstream gating is unchanged.
rwv_stage_status_label <- function(st) {
  if (!identical(st$status, "running") || is.null(st$pid) || is.null(st$host) ||
      !identical(st$host, rwv_stage_host())) return(st$status)
  alive <- tryCatch(isTRUE(tools::pskill(as.integer(st$pid), 0L)), error = function(e) TRUE)
  if (alive) "running" else paste0("ended without finishing: process ", st$pid,
    " is gone, so the run stopped on an error or was interrupted; render the step to see the error")
}

# Entries of the step directory that belong to a published result (not the
# hidden control files and folders of this mechanism).
rwv_stage_result_entries <- function(dir) {
  e <- list.files(dir, all.files = TRUE, no.. = TRUE)
  e[!startsWith(e, ".rwv-") & e != ".DS_Store"]
}

rwv_stage_open <- function(final, run_id, mode) {
  dir.create(final, recursive = TRUE, showWarnings = FALSE)
  rwv_stage_recover(final)
  staging <- rwv_stage_child(final, rwv_stage_names$staging)
  if (dir.exists(staging)) unlink(staging, recursive = TRUE)
  dir.create(staging)
  rwv_stage_status_write(final, list(status = "running", run_id = run_id, mode = mode, started = rwv_time(),
                                     pid = Sys.getpid(), host = rwv_stage_host()))
  staging
}

# Some managed macOS filesystems permit file moves but deny renaming the
# generated review-candidate directory (EPERM). Preserve the same journal and
# record commit point: copy and hash-verify the entire directory before removing
# any source files. Empty directory shells may remain when OS cleanup is denied.
# This fallback is limited to the registered generated bundle directory; it is
# not used for raw data, project inputs, symlinks, or nonempty destinations.
rwv_stage_is_link <- function(path) {
  target <- Sys.readlink(path)
  !is.na(target) && nzchar(target)
}

rwv_stage_tree_entries <- function(path) {
  if (rwv_stage_is_link(path)) rwv_fail("Refusing a symlink in the generated bundle copy: ", path)
  if (!dir.exists(path)) return(character())
  result <- character()
  visit <- function(dir, prefix = "") {
    for (e in list.files(dir, all.files = TRUE, no.. = TRUE)) {
      p <- file.path(dir, e)
      if (rwv_stage_is_link(p)) rwv_fail("Refusing a symlink in the generated bundle copy: ", p)
      rel <- if (nzchar(prefix)) paste(prefix, e, sep = "/") else e
      result <<- c(result, rel)
      if (dir.exists(p)) visit(p, rel)
    }
  }
  visit(path)
  result
}

rwv_stage_move <- function(from, to) {
  if (isTRUE(suppressWarnings(file.rename(from, to)))) return(TRUE)
  if (!dir.exists(from) || basename(from) != "review-candidate" ||
      basename(to) != "review-candidate" || rwv_stage_is_link(from) || rwv_stage_is_link(to)) return(FALSE)
  a <- dirname(from)
  b <- dirname(to)
  final <- if (basename(a) %in% c(rwv_stage_names$previous, rwv_stage_names$staging)) dirname(a) else a
  pairs <- list(c(final, file.path(final, rwv_stage_names$previous)),
                c(file.path(final, rwv_stage_names$staging), final),
                c(file.path(final, rwv_stage_names$previous), final))
  if (basename(final) != "900-publication-bundle" ||
      !any(vapply(pairs, function(pair) identical(c(a, b), pair), logical(1))) ||
      any(vapply(unique(c(final, a, b)), rwv_stage_is_link, logical(1)))) return(FALSE)
  entries <- rwv_stage_tree_entries
  src <- entries(from)
  src_files <- src[!dir.exists(file.path(from, src))]
  if (dir.exists(to)) {
    dst <- entries(to)
    if (any(!dir.exists(file.path(to, dst)))) return(FALSE)
  } else if (file.exists(to)) return(FALSE)
  plan <- file.path(dirname(to), ".rwv-copy-plan-review-candidate.json")
  operation <- if (basename(dirname(from)) == rwv_stage_names$previous) "restore" else
    if (basename(dirname(to)) == rwv_stage_names$previous) "backup" else "publish"
  jsonlite::write_json(list(operation = operation, files = as.list(src_files),
                            sha256 = as.list(vapply(file.path(from, src_files), rwv_sha256, character(1)))),
                       plan, auto_unbox = TRUE, pretty = TRUE)
  dir.create(to, recursive = TRUE, showWarnings = FALSE)
  dirs <- src[dir.exists(file.path(from, src))]
  for (d in dirs) dir.create(file.path(to, d), recursive = TRUE, showWarnings = FALSE)
  for (f in src_files) {
    if (!file.copy(file.path(from, f), file.path(to, f), overwrite = FALSE,
                   copy.mode = TRUE, copy.date = TRUE)) return(FALSE)
  }
  dst <- entries(to)
  dst_files <- dst[!dir.exists(file.path(to, dst))]
  if (!identical(sort(src_files), sort(dst_files))) return(FALSE)
  for (f in src_files) {
    if (!identical(rwv_sha256(file.path(from, f)), rwv_sha256(file.path(to, f)))) return(FALSE)
  }
  # During recovery retain the authoritative backup until common cleanup.
  # Keep the restore plan too: if cleanup is interrupted after deleting part of
  # the backup, a re-entered recovery can recognize and protect the restored copy.
  if (operation == "restore") {
    message("Restored generated directory from verified backup; backup retained until cleanup.")
    return(TRUE)
  }
  # The complete verified copy now exists. A failed removal leaves the journal
  # uncommitted and both copies available for the ordinary recovery mechanism.
  if (length(src_files) && !all(file.remove(file.path(from, src_files)))) return(FALSE)
  remaining <- entries(from)
  if (any(!dir.exists(file.path(from, remaining)))) return(FALSE)
  file.remove(plan)
  message("Published-directory move used a verified file copy (OS rename denied): ", basename(from))
  TRUE
}

rwv_stage_publish <- function(final, staging, run_id, record) {
  new_entries <- rwv_stage_result_entries(staging)
  old_entries <- rwv_stage_result_entries(final)
  journal <- file.path(final, rwv_stage_names$journal)
  jsonlite::write_json(list(run_id = run_id, phase = "publishing", new_entries = as.list(new_entries),
                            old_entries = as.list(old_entries), started = rwv_time()),
                       journal, auto_unbox = TRUE, pretty = TRUE)
  previous <- rwv_stage_child(final, rwv_stage_names$previous)
  if (dir.exists(previous)) unlink(previous, recursive = TRUE)
  dir.create(previous)
  # Optional failure-injection hooks for transaction verification.
  stop_aside <- getOption("rwv.test_stop_aside_after", Inf)
  stop_new <- getOption("rwv.test_stop_publish_after", Inf)
  for (i in seq_along(old_entries)) {
    if (i - 1L >= stop_aside) stop("simulated interruption while moving the previous result aside", call. = FALSE)
    e <- old_entries[i]
    if (!rwv_stage_move(file.path(final, e), file.path(previous, e))) rwv_fail("Could not move ", e, " aside in ", final, ".")
  }
  publish <- setdiff(new_entries, "step-record.json")
  for (i in seq_along(publish)) {
    if (i - 1L >= stop_new) stop("simulated interruption during publication", call. = FALSE)
    e <- publish[i]
    if (!rwv_stage_move(file.path(staging, e), file.path(final, e))) rwv_fail("Could not publish ", e, " in ", final, ".")
  }
  # Commit point: the record is renamed into place in one step.
  tmp <- file.path(staging, "step-record.json.tmp")
  jsonlite::write_json(record, tmp, auto_unbox = TRUE, pretty = TRUE, digits = NA)
  if (!file.rename(tmp, file.path(final, "step-record.json"))) rwv_fail("Could not commit step-record.json in ", final, ".")
  rwv_stage_cleanup(final, run_id, "complete")
}

rwv_stage_cleanup <- function(final, run_id, status, reason = NULL) {
  for (d in c(rwv_stage_names$previous, rwv_stage_names$staging)) {
    p <- rwv_stage_child(final, d)
    if (dir.exists(p)) unlink(p, recursive = TRUE)
  }
  j <- file.path(final, rwv_stage_names$journal)
  if (file.exists(j)) file.remove(j)
  copy_plan <- file.path(final, ".rwv-copy-plan-review-candidate.json")
  if (file.exists(copy_plan)) file.remove(copy_plan)
  fields <- list(status = status, run_id = run_id, finished = rwv_time())
  if (!is.null(reason)) fields$reason <- reason
  rwv_stage_status_write(final, fields)
  invisible(status)
}

# Finish or roll back an interrupted publication. Returns "none", "completed"
# (the new record had been committed) or "restored" (previous result back).
rwv_stage_recover <- function(final) {
  j <- file.path(final, rwv_stage_names$journal)
  if (!file.exists(j)) return("none")
  journal <- jsonlite::read_json(j)
  rec <- file.path(final, "step-record.json")
  committed <- file.exists(rec) && identical(jsonlite::read_json(rec)$run_id, journal$run_id)
  if (committed) {
    rwv_stage_cleanup(final, journal$run_id, "complete")
    return("completed")
  }
  previous <- rwv_stage_child(final, rwv_stage_names$previous)
  old_entries <- unlist(journal$old_entries)
  moved_aside <- if (dir.exists(previous)) rwv_stage_result_entries(previous) else character()
  restored_candidate <- FALSE
  restore_plan <- file.path(final, ".rwv-copy-plan-review-candidate.json")
  if (file.exists(restore_plan)) {
    plan <- jsonlite::read_json(restore_plan)
    if (identical(plan$operation, "restore")) {
      fs <- as.character(unlist(plan$files))
      hashes <- as.character(unlist(plan$sha256))
      matches <- function(dir) {
        actual <- rwv_stage_tree_entries(dir)
        actual <- actual[!dir.exists(file.path(dir, actual))]
        identical(sort(fs), sort(actual)) &&
          identical(unname(vapply(file.path(dir, fs), rwv_sha256, character(1))), unname(hashes))
      }
      restored_candidate <- matches(file.path(final, "review-candidate"))
      if (!restored_candidate && !matches(file.path(previous, "review-candidate"))) {
        rwv_fail("Neither retained bundle copy matches the recovery plan; refusing destructive recovery in ", final, ".")
      }
      if (restored_candidate) moved_aside <- setdiff(moved_aside, "review-candidate")
    }
  }
  # A partial backup is not authoritative. During interrupted cleanup, however,
  # the complete hash-verified restored target is already the protected copy.
  copy_plan <- file.path(previous, ".rwv-copy-plan-review-candidate.json")
  if (file.exists(copy_plan) && !restored_candidate) {
    plan <- jsonlite::read_json(copy_plan)
    fs <- as.character(unlist(plan$files))
    hashes <- as.character(unlist(plan$sha256))
    backup <- file.path(previous, "review-candidate")
    actual <- rwv_stage_tree_entries(backup)
    actual <- actual[!dir.exists(file.path(backup, actual))]
    if (!identical(sort(fs), sort(actual)) ||
        !identical(unname(vapply(file.path(backup, fs), rwv_sha256, character(1))), unname(hashes))) {
      rwv_fail("The generated-directory backup copy is incomplete; retained originals were not removed. ",
               "Verify the copy journal before retrying recovery in ", final, ".")
    }
  }
  for (e in rwv_stage_result_entries(final)) {
    # An old entry that was not yet moved aside stays; everything else in the
    # step directory is part of the unfinished new result.
    if ((e %in% old_entries && !e %in% moved_aside) ||
        (e == "review-candidate" && restored_candidate)) next
    unlink(file.path(final, e), recursive = TRUE)
  }
  for (e in moved_aside) {
    if (!rwv_stage_move(file.path(previous, e), file.path(final, e))) {
      rwv_fail("Could not restore ", e, " after interrupted publication in ", final, ".")
    }
  }
  rwv_stage_cleanup(final, journal$run_id, "failed", reason = "publication was interrupted; the previous result was restored")
  "restored"
}

# Downstream guard: refuse a step whose latest run did not finish, even though
# its previous successful result is still on disk.
rwv_stage_guard <- function(final, from, record) {
  if (file.exists(file.path(final, rwv_stage_names$journal))) {
    rwv_fail("The publication of ", from, " was interrupted. Render ", from, " again; it restores or completes the result first.")
  }
  st <- rwv_stage_status_read(final)
  if (!is.null(st) && st$status %in% c("running", "failed") && !identical(st$run_id, record$run_id)) {
    rwv_fail("The latest run of ", from, " (", st$run_id, ", status: ", rwv_stage_status_label(st),
             if (!is.null(st$reason)) paste0(", ", st$reason) else "", ") did not finish. ",
             "Its previous successful result (run ", record$run_id, ") is kept but is not used for this step. ",
             "Render ", from, " again and wait for it to finish, or run source(\"dev/render.R\").")
  }
  invisible(TRUE)
}

# ---------------------------------------------------------------------------
# Automatic input verification (010) for single-step renders.
#
# 010-input-manifest verifies every project input and migrated raw input. In
# the full launcher it is the first step. When one step is rendered on its own
# (RStudio Render, dev/render.R), rwv_step_begin() calls this: if the
# 010 record is missing, unfinished or any input it recorded has changed, 010
# is re-rendered first in its own Quarto process (it writes only its own
# directory), so the user never has to render 010 by hand.

rwv_inputs_current <- function(root) {
  d <- file.path(root, "analyses", "data", "010-input-manifest")
  rec_path <- file.path(d, "step-record.json")
  if (!file.exists(rec_path) || file.exists(file.path(d, ".rwv-publish.json"))) return(FALSE)
  st <- rwv_stage_status_read(d)
  if (!is.null(st) && !identical(st$status, "complete")) return(FALSE)
  rec <- jsonlite::read_json(rec_path)
  if (!identical(rec$status, "complete")) return(FALSE)
  if (length(rwv_source_changes(root, "010-input-manifest", rec))) return(FALSE)
  for (i in rec$inputs) {
    p <- file.path(root, i$path)
    if (!file.exists(p) || !identical(rwv_sha256(p), i$sha256)) return(FALSE)
  }
  TRUE
}

rwv_inputs_ensure <- function(root, name, mode) {
  if (identical(name, "010-input-manifest") || identical(mode, "launcher") || rwv_inputs_current(root)) return(invisible(FALSE))
  quarto <- file.path(Sys.getenv("QUARTO_BIN_PATH"), "quarto")
  if (!file.exists(quarto)) quarto <- unname(Sys.which("quarto"))
  if (!nzchar(quarto)) rwv_fail("The input check 010-input-manifest is out of date and Quarto was not found to re-run it.")
  message("Inputs changed or 010-input-manifest has not run: re-rendering 010 first ...")
  # The child render must not inherit this render's Quarto document context.
  qvars <- grep("^QUARTO_", names(Sys.getenv()), value = TRUE)
  qvars <- setdiff(qvars, c("QUARTO_PATH", "QUARTO_BIN_PATH"))
  saved <- Sys.getenv(qvars, names = TRUE)
  Sys.unsetenv(qvars)
  old <- setwd(file.path(root, "analyses"))
  on.exit({ setwd(old); if (length(saved)) do.call(Sys.setenv, as.list(saved)) }, add = TRUE)
  status <- system2(quarto, c("render", "010-input-manifest.qmd", "--execute", "--no-cache", "--quiet"))
  if (!identical(as.integer(status), 0L) || !rwv_inputs_current(root)) {
    rwv_fail("Re-rendering 010-input-manifest failed (exit ", status, "); open analyses/010-input-manifest.md for the reason.")
  }
  invisible(TRUE)
}

