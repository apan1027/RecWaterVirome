rwv_quarto_version <- function() {
  candidates <- c(
    Sys.getenv("QUARTO_PATH", unset = ""),
    if (nzchar(Sys.getenv("QUARTO_BIN_PATH"))) file.path(Sys.getenv("QUARTO_BIN_PATH"), "quarto") else "",
    unname(Sys.which("quarto"))
  )
  candidates <- candidates[nzchar(candidates) & file.exists(candidates)]
  if (!length(candidates)) return(NA_character_)
  out <- tryCatch(system2(candidates[1], "--version", stdout = TRUE, stderr = FALSE), error = function(e) NA_character_)
  if (length(out)) out[1] else NA_character_
}

