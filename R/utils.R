# Validate the qproj bindings of the current QMD against the manifest, open a
# staging folder for the new outputs (the previous result is kept until the
# new one is published) and return a mutable step handle. The QMD then uses
# path_target <- step$path_target.
rwv_step_begin <- function(name, path_target) {
  root <- rwv_root()
  wf <- rwv_workflow_read(root)
  spec <- rwv_workflow_step(wf, name)
  workflow_dir <- file.path(root, wf$workflow_dir)
  if (!identical(rwv_norm(here::here()), rwv_norm(workflow_dir))) {
    rwv_fail("here() is anchored at ", here::here(), ", not at ", workflow_dir,
             ". Run the params and setup chunks of ", name, ".qmd first.")
  }
  if (!identical(rwv_norm(path_target()), rwv_norm(file.path(workflow_dir, "data", name)))) {
    rwv_fail("path_target() points at ", path_target(), ", not at this step's own directory. ",
             "Re-run the params and setup chunks of ", name, ".qmd.")
  }
  document <- Sys.getenv("QUARTO_DOCUMENT_FILE", unset = "")
  if (!nzchar(document)) document <- rwv_chr(knitr::current_input())
  if (length(document) && nzchar(document) &&
    !identical(tools::file_path_sans_ext(basename(document)), name)) {
    rwv_fail("params$name is '", name, "' but the document being rendered is ", document, ".")
  }

  run_id <- Sys.getenv("RWV_RUN_ID", unset = "")
  mode <- if (nzchar(run_id)) {
    "launcher"
  } else if (isTRUE(getOption("knitr.in.progress"))) {
    if (nzchar(Sys.getenv("QUARTO_DOCUMENT_FILE", unset = ""))) "quarto-render" else "knitr-render"
  } else {
    "interactive"
  }
  if (!nzchar(run_id)) run_id <- paste0(mode, "-", format(Sys.time(), "%Y%m%dT%H%M%S"))

  # Single-step renders re-run the input check (010) first when it is stale.
  rwv_inputs_ensure(root, name, mode)
  # New outputs go to a staging folder; the previous result stays in place
  # until rwv_step_finish() has checked and published the new one.
  final <- path_target()
  staging <- rwv_stage_open(final, run_id, mode)

  step <- new.env(parent = emptyenv())
  step$final_dir <- final
  step$staging_dir <- staging
  step$published <- FALSE
  # Same calling convention as qproj's path_target(): no argument gives the
  # directory, arguments are joined into one path.
  step$path_target <- function(...) {
    base <- if (isTRUE(step$published)) step$final_dir else step$staging_dir
    if (!length(list(...))) base else do.call(file.path, c(list(base), list(...)))
  }
  step$name <- name
  step$spec <- spec
  step$workflow <- wf
  step$root <- root
  step$run_id <- run_id
  step$mode <- mode
  step$started <- Sys.time()
  step$inputs <- list()
  step$source_contract <- "rwv-source-public-v2"
  step$sources <- rwv_source_snapshot(root, name)
  step
}

rwv_step_note_input <- function(step, kind, path, sha256) {
  step$inputs[[length(step$inputs) + 1L]] <- list(kind = kind, path = path, sha256 = sha256)
  invisible(NULL)
}

# Read a declared output of an earlier step. Unlike qproj's path_source(),
# which only warns about order problems, every check here is an error.
rwv_step_input <- function(step, path_source, from, file) {
  spec <- step$spec
  if (!from %in% rwv_chr(spec$depends_on)) {
    rwv_fail(step$name, " does not declare depends_on: ", from, " in analyses/R/steps.yml.")
  }
  declared <- vapply(spec$upstream_inputs, function(u) identical(u$step, from) && identical(u$file, file), logical(1))
  if (!any(declared)) {
    rwv_fail(step$name, " does not declare upstream input ", from, "/", file, " in analyses/R/steps.yml.")
  }
  if (rwv_step_number(from) >= rwv_step_number(step$name)) {
    rwv_fail(from, " is not an earlier step than ", step$name, ".")
  }
  locate <- function(f) {
    withCallingHandlers(path_source(from, f),
      warning = function(w) rwv_fail("path_source(): ", conditionMessage(w))
    )
  }
  path <- locate(file)
  record <- rwv_step_record_read(locate("step-record.json"), from)
  source_changes <- rwv_source_changes(step$root, from, record)
  if (length(source_changes)) {
    rwv_fail("Upstream ", from, " has changed or unverified executable sources (",
             paste(source_changes, collapse = ", "), "). Render it before using its outputs.")
  }
  if (identical(step$mode, "launcher") && !identical(record$run_id, step$run_id)) {
    rwv_fail("Upstream ", from, " comes from run ", record$run_id, ", not from the current launcher run ",
             step$run_id, "; refusing stale output.")
  }
  if (!file.exists(path)) rwv_fail("Missing upstream file ", from, "/", file, ". Render ", from, " first.")
  expected <- rwv_record_hash(record, file)
  actual <- rwv_sha256(path)
  if (!identical(expected, actual)) {
    rwv_fail("Upstream file ", from, "/", file, " does not match its step-record.json (recorded ", expected,
             ", found ", actual, "): tampered or stale. Re-render ", from, ".")
  }
  rwv_step_note_input(step, "upstream", paste0(from, "/", file), actual)
  path
}

# Read a declared project file and require that it is byte-identical to the
# version inventoried by 010-input-manifest.
rwv_project_input <- function(step, file, input_manifest) {
  if (!file %in% rwv_chr(step$spec$project_inputs)) {
    rwv_fail(step$name, " does not declare project input ", file, " in analyses/R/steps.yml.")
  }
  path <- file.path(step$root, file)
  if (!file.exists(path)) rwv_fail("Missing project input ", file, ".")
  row <- input_manifest[input_manifest$path == file, , drop = FALSE]
  if (nrow(row) != 1L) rwv_fail(file, " is not inventoried by 010-input-manifest.")
  actual <- rwv_sha256(path)
  if (!identical(row$sha256, actual)) {
    rwv_fail(file, " changed after 010-input-manifest recorded it (recorded ", row$sha256, ", now ", actual,
             "). Re-run the workflow from 010 with source(\"dev/render.R\"); ",
             "010 checks the file against analyses/data/source-checksums.tsv.")
  }
  rwv_step_note_input(step, "project", file, actual)
  path
}

rwv_step_record_read <- function(path, from) {
  if (file.exists(file.path(dirname(path), rwv_stage_names$journal))) {
    rwv_fail("The publication of ", from, " was interrupted. Render ", from, " again; it restores or completes the result first.")
  }
  if (!file.exists(path)) {
    rwv_fail("Upstream step ", from, " has no step-record.json, so it has not completed. Render ", from,
             " first, or run source(\"dev/render.R\") from the project root.")
  }
  record <- jsonlite::read_json(path)
  if (!identical(record$status, "complete") || !identical(record$step, from)) {
    rwv_fail("step-record.json of ", from, " is not a complete record for that step.")
  }
  rwv_stage_guard(dirname(path), from, record)
  record
}

rwv_record_hash <- function(record, file) {
  hit <- Filter(function(o) identical(o$file, file), record$outputs)
  if (length(hit) != 1L) rwv_fail("step-record.json of ", record$step, " does not list ", file, ".")
  hit[[1]]$sha256
}

# Check that exactly the declared outputs exist, hash them and write the
# step record that downstream steps and the launcher rely on.
rwv_step_finish <- function(step, path_target, raw_manifest = NULL) {
  source_changes <- rwv_source_changes(step$root, step$name,
                                      list(source_contract = step$source_contract, sources = step$sources))
  if (length(source_changes)) rwv_fail("Executable sources changed during ", step$name, ": ",
                                      paste(source_changes, collapse = ", "), ". Previous outputs are preserved.")
  outputs <- rwv_chr(step$spec$outputs)
  optional <- rwv_chr(step$spec$optional_outputs)
  optional <- optional[file.exists(rwv_target_files(path_target, optional))]
  written <- c(outputs, optional)
  paths <- rwv_target_files(path_target, written)
  missing <- outputs[!file.exists(rwv_target_files(path_target, outputs))]
  if (length(missing)) rwv_fail(step$name, " did not write declared outputs: ", paste(missing, collapse = ", "), ".")
  dirs <- rwv_chr(step$spec$output_dirs)
  present <- list.files(path_target(), all.files = TRUE, recursive = TRUE, no.. = TRUE)
  present <- present[basename(present) != ".DS_Store"]
  in_dirs <- Reduce(`|`, lapply(dirs, function(d) startsWith(present, paste0(d, "/"))), rep(FALSE, length(present)))
  extra <- setdiff(present[!in_dirs], c(written, "step-record.json"))
  if (length(extra)) {
    rwv_fail("Undeclared files in the target directory of ", step$name, ": ", paste(extra, collapse = ", "),
             ". Declare them in analyses/R/steps.yml or remove them.")
  }
  for (d in dirs) {
    rwv_output_dir_path(path_target, d)
    if (!any(startsWith(present, paste0(d, "/")))) rwv_fail(step$name, ": declared output directory ", d, " is empty.")
  }
  # Every raw input registered for this step must actually have been read.
  if (!is.null(raw_manifest)) {
    mine <- raw_manifest$path[raw_manifest$consumer_step == step$name]
    read <- vapply(Filter(function(i) i$kind %in% c("raw", "raw_not_used_in_active_version"), step$inputs), function(i) i$path, character(1))
    unread <- setdiff(mine, read)
    if (length(unread)) {
      rwv_fail(step$name, " registered but never read these raw inputs: ", paste(unread, collapse = ", "),
               ". Use them or remove them from the input list.")
    }
  }
  bundled <- present[in_dirs]
  hashes <- rwv_sha256(paths)
  sizes <- file.size(paths)
  record <- list(
    step = step$name,
    status = "complete",
    run_id = step$run_id,
    mode = step$mode,
    qmd = step$spec$qmd,
    source_contract = step$source_contract,
    sources = step$sources,
    started = rwv_time(step$started),
    finished = rwv_time(),
    inputs = step$inputs,
    outputs = lapply(seq_along(written), function(i) list(file = written[i], bytes = sizes[i], sha256 = hashes[i])),
    output_dir_files = if (length(bundled)) {
      bundled_paths <- file.path(path_target(), bundled)
      bundled_sha <- rwv_sha256(bundled_paths)
      lapply(seq_along(bundled), function(i) {
        list(file = bundled[i], bytes = file.size(bundled_paths[i]), sha256 = bundled_sha[i])
      })
    } else list()
  )
  if (identical(rwv_norm(path_target()), rwv_norm(step$final_dir))) {
    rwv_fail(step$name, ": path_target still points at the published directory; the step-guard chunk must set ",
             "path_target <- step$path_target.")
  }
  rwv_stage_publish(step$final_dir, step$staging_dir, step$run_id, record)
  step$published <- TRUE
  data.frame(file = written, bytes = sizes, sha256 = hashes)
}

# Used by dev/render.R after each render: the record must come from this
# launcher run, match the manifest and the files on disk, and the report
# must have been rendered during the run.
rwv_step_verify <- function(root, id, run_id, since) {
  wf <- rwv_workflow_read(root)
  spec <- rwv_workflow_step(wf, id)
  dir <- file.path(root, wf$workflow_dir, "data", id)
  record <- rwv_step_record_read(file.path(dir, "step-record.json"), id)
  if (!identical(record$run_id, run_id)) {
    rwv_fail(id, ": step-record.json is from run ", record$run_id, ", expected ", run_id, ".")
  }
  outputs <- rwv_chr(spec$outputs)
  listed <- vapply(record$outputs, function(o) o$file, character(1))
  if (!all(outputs %in% listed) || !all(setdiff(listed, outputs) %in% rwv_chr(spec$optional_outputs))) {
    rwv_fail(id, ": step-record.json outputs differ from analyses/R/steps.yml.")
  }
  paths <- file.path(dir, listed)
  actual <- rwv_sha256(paths)
  expected <- vapply(listed, function(f) rwv_record_hash(record, f), character(1), USE.NAMES = FALSE)
  if (!identical(expected, actual)) rwv_fail(id, ": outputs changed after step-record.json was written.")
  recorded <- vapply(record$output_dir_files, function(o) o$file, character(1))
  for (o in record$output_dir_files) {
    f <- file.path(dir, o$file)
    if (!file.exists(f) || !identical(rwv_sha256(f), o$sha256)) {
      rwv_fail(id, ": bundled file ", o$file, " is missing or changed after step-record.json was written.")
    }
  }
  for (d in rwv_chr(spec$output_dirs)) {
    now <- list.files(file.path(dir, d), recursive = TRUE, all.files = TRUE, no.. = TRUE)
    now <- file.path(d, now[basename(now) != ".DS_Store"])
    if (!setequal(now, recorded[startsWith(recorded, paste0(d, "/"))])) {
      rwv_fail(id, ": the contents of ", d, "/ differ from step-record.json.")
    }
  }
  outputs <- listed
  report <- file.path(root, sub("\\.qmd$", ".md", spec$qmd))
  if (!file.exists(report) || file.mtime(report) < since) {
    rwv_fail(id, ": rendered report ", report, " is missing or older than this run.")
  }
  data.frame(step = id, file = outputs, bytes = file.size(paths), sha256 = actual)
}

