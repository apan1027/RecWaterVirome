# Public snapshots have a new source contract. Historical records must not be
# relabelled as executions of these sources. Changed inputs always invalidate.
rwv_report_sync <- function(root, id) {
  d <- file.path(root, "analyses/data", id)
  rec <- file.path(d, "step-record.json")
  md <- file.path(root, "analyses", paste0(id, ".md"))
  if (!file.exists(rec)) return(paste0(id, ": no current step record; supply inputs and render this step"))
  if (!file.exists(md)) return(paste0(id, ": Markdown report missing"))
  record <- rwv_step_record_read(rec, id)
  text <- paste(readLines(md, warn = FALSE), collapse = "\n")
  hashes <- substr(vapply(record$outputs, function(x) x$sha256, ""), 1L, 16L)
  missing <- hashes[!vapply(hashes, function(x) grepl(x, text, fixed = TRUE), logical(1))]
  if (length(missing)) paste0(id, ": Markdown does not contain this execution's output hashes") else character()
}

rwv_step_inputs_changed <- function(root, id) {
  path <- file.path(root, "analyses/data", id, "step-record.json")
  if (!file.exists(path)) return(paste0(id, "/step-record.json missing"))
  record <- rwv_step_record_read(path, id)
  changed <- rwv_source_changes(root, id, record)
  for (input in record$inputs) {
    p <- if (identical(input$kind, "upstream")) file.path(root, "analyses/data", input$path) else file.path(root, input$path)
    if (!file.exists(p) || !identical(rwv_sha256(p), input$sha256)) changed <- c(changed, input$path)
  }
  unique(changed)
}

rwv_step_sync_problems <- function(root, id) {
  bad <- rwv_report_sync(root, id)
  changes <- rwv_step_inputs_changed(root, id)
  if (length(changes)) bad <- c(bad, paste0(id, ": changed/unverified sources or inputs: ", paste(head(changes, 4L), collapse = ", ")))
  d <- file.path(root, "analyses/data", id)
  state <- rwv_stage_status_read(d)
  if (file.exists(file.path(d, ".rwv-publish.json")) || (!is.null(state) && !identical(state$status, "complete")))
    bad <- c(bad, paste0(id, ": unfinished output transaction"))
  bad
}

rwv_sync_status <- function(root, strict = TRUE, step_problems = rwv_step_sync_problems) {
  ids <- rwv_workflow_ids(rwv_workflow_read(root))
  list(problems = unlist(lapply(ids, function(id) step_problems(root, id))), notes = character(), checked = ids)
}
