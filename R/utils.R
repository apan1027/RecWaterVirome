  si <- sessioninfo::session_info(info = c("platform", "packages"))
  header <- c(paste0("# Written ", rwv_time()), if (length(extra)) paste0("# ", names(extra), ": ", extra))
  writeLines(c(header, "", utils::capture.output(print(si))), path)
  invisible(path)
}

